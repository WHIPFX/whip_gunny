-- Weapons: one entry per weapon item, keyed by the item.
--
-- Every weapon has:
--   weight, description, label   the item: kg, its card's text, its name. weight if not given: 2.0 a gun, 1.0 melee,
--                                0.5 a throwable, 3.0 the jerry can
--   hash                         the GTA weapon it draws (gunny's own add-ons are WEAPON_WHIP_*)
--   prop                         its model lying on the ground
-- A gun with a magazine also has:
--   caliber                      the ammunition it fires (items/calibers.lua)
--   compatibleMags               the magazines it takes (items/magazines.lua)
--   defaultClipComponent         the GTA magazine shown when its own magazine has no component
--   reloadTime                   ms; also the least a reload takes in a seat
-- A gun with no magazine (revolvers, tube-fed and break-action shotguns, launchers) has caliber and reloadTime, and:
--   magless = true
--   internalCapacity             the rounds it holds, loaded straight in
--   loopedReload = true          loaded a shell at a time (needs UseLoopedReloadAnim in its weapon meta, and reload_loop clips)
-- The other kinds:
--   melee = true                 swung: no ammunition, magazine, reload or attachments
--   fuelCan = true               the jerry can: its ammunition is the fuel in it (metadata `fuel`, 0-100%), and
--                                fuelCapacity is how much of a car's tank (100) a full can holds
--   throwable = true             a stack, and the stack is what the hand holds; maxStack (25 if not given)
-- reloadTime, internalCapacity and a magazine's capacity are also per-item settings on /whip's Items page.

